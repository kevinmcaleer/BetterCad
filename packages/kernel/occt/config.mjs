#!/usr/bin/env node
/**
 * Writes the custom OpenCascade build config (#43) from what the kernel uses: every OCCT class the code names
 * (`oc.X`, or a type imported from replicad-opencascadejs), plus the classes those classes' methods take and return,
 * `DEPTH` steps out, so a value the code gets back can still be used. Classes outside the stock build are left out.
 *
 *   node packages/kernel/occt/config.mjs [--depth 2] [--out packages/kernel/occt/build/bettercad.yml]
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const arg = (name, d) => (args.includes(name) ? args[args.indexOf(name) + 1] : d);
const DEPTH = Number(arg("--depth", 2));
const out = arg("--out", join(here, "build", "bettercad.yml"));

const require = createRequire(import.meta.url);
const dts = readFileSync(join(dirname(require.resolve("replicad-opencascadejs/package.json")), "dist", "replicad_single.d.ts"), "utf8");

/** Every class and enum the stock build declares (an enum is a `declare const`), with the names its body mentions. */
const decls = new Map();
/** Each class's base class: its inherited methods are part of it, so a base is kept whenever the class is. */
const base = new Map();
const classes = new Set();
for (const m of dts.matchAll(/^(?:export )?declare (class|enum|type|interface|const) ([A-Za-z0-9_]+)([^\n]*)\n([\s\S]*?)^}/gm)) {
  m.shift();
  if (m[0] === "class") classes.add(m[1]);
  // gp_ types start lower case.
  decls.set(
    m[1],
    new Set([...(m[2] + m[3]).matchAll(/\b([A-Za-z][A-Za-z0-9]*_[A-Za-z0-9_]+|TopoDS|BRepGProp|BRepBndLib|BRepTools|Precision)\b/g)].map((x) => x[1])),
  );
  const ext = /extends ([A-Za-z0-9_]+)/.exec(m[2]);
  if (ext) base.set(m[1], ext[1]);
}
/** A class with all its bases. */
const lineage = (c) => {
  const out = [];
  for (let x = c; x && !out.includes(x); x = base.get(x)) out.push(x);
  return out;
};

const src = join(here, "..", "src");
const files = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? files(join(dir, e.name)) : e.name.endsWith(".ts") ? [join(dir, e.name)] : []));
const used = new Set();
for (const f of files(src)) {
  const text = readFileSync(f, "utf8");
  for (const m of text.matchAll(/\boc\.([A-Za-z0-9_]+)/g)) if (decls.has(m[1])) used.add(m[1]);
  for (const m of text.matchAll(/import type \{([^}]+)\} from "replicad-opencascadejs"/g))
    for (const n of m[1].split(",").map((s) => s.trim())) if (decls.has(n)) used.add(n);
}

const keep = new Set([...used].flatMap(lineage));
let edge = [...keep];
for (let d = 0; d < DEPTH; d++) {
  const next = [];
  for (const c of edge)
    for (const n of decls.get(c) ?? [])
      for (const l of decls.has(n) ? lineage(n) : [])
        if (!keep.has(l)) {
          keep.add(l);
          next.push(l);
        }
  edge = next;
}
// Classes and enums are bound by name; the runtime helpers are not. An enum declared inside a class (gp_Dir_D is
// gp_Dir::D) comes with its class and can't be bound alone.
const nested = (n) => !classes.has(n) && classes.has(n.slice(0, n.lastIndexOf("_")));
const bindings = [...keep].filter((n) => /_|^TopoDS$|^BRepGProp$|^BRepBndLib$|^BRepTools$|^Precision$/.test(n) && !nested(n)).sort();
const skipped = [...keep].filter(nested);

const flags = [
  "-fwasm-exceptions",
  "-sEXPORT_EXCEPTION_HANDLING_HELPERS",
  "-sEXPORT_ES6=1",
  "-sMODULARIZE",
  "-sALLOW_MEMORY_GROWTH=1",
  "-sINITIAL_MEMORY=100MB",
  "-sMAXIMUM_MEMORY=2GB",
  '-sEXPORTED_RUNTIME_METHODS=["FS","wasmMemory","getExceptionMessage","incrementExceptionRefcount","decrementExceptionRefcount"]',
  "-sENVIRONMENT=web,worker,node",
  "--no-entry",
  "-sERROR_ON_UNDEFINED_SYMBOLS=0",
  "-sEVAL_CTORS=2",
  "-Oz",
];
const yaml = [
  "# Generated by packages/kernel/occt/config.mjs (#43). Do not edit by hand.",
  `# ${used.size} classes named in the kernel, ${bindings.length} with what they take and return (depth ${DEPTH}).`,
  "mainBuild:",
  "  name: bettercad_occt.js",
  "  bindings:",
  ...bindings.map((b) => `    - symbol: ${b}`),
  "  emccFlags:",
  ...flags.map((f) => `    - '${f.replace(/'/g, "''")}'`),
  "",
].join("\n");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, yaml);
console.log(`${used.size} named, ${bindings.length} bound of ${decls.size} in the stock build -> ${out}`);
if (skipped.length) console.log(`Left to their classes: ${skipped.join(", ")}`);
